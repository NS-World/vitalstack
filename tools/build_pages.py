#!/usr/bin/env python3
"""Build the theme-managed pages (cheat sheets, free tools, mock tests and roadmaps) into theme data.

Sources: content/site-pages/<group>/<slug>.md with front matter:

    ---
    title: Python Cheat Sheet
    slug: python-cheat-sheet
    parent: cheat-sheets          # hub page slug (cheat-sheets, tools, mock-tests or roadmaps)
    template: page-cheat-sheet.php
    path: java                    # mock tests only: learning path whose quiz questions it uses
    icon: 🐍
    order: 10
    excerpt: One-line description for cards and search results.
    ---
    Markdown body (same syntax as lessons).

Outputs:
    wp-content/themes/vitalstack/data/pages/<slug>.html   rendered body
    wp-content/themes/vitalstack/data/pages/index.php     list of pages for the setup wizard

Pages are created by Appearance → VitalStack Setup. While a page's content is
empty, the theme shows the body from data/pages/, so theme updates refresh it.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from lessons_to_wxr import markdown_to_blocks, parse_front_matter  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "content" / "site-pages"
OUT = ROOT / "wp-content" / "themes" / "vitalstack" / "data" / "pages"


def php_str(s):
    return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    pages = []
    for md in sorted(SRC.glob("*/*.md")):
        meta, body = parse_front_matter(md.read_text(encoding="utf-8"), md)
        for key in ("title", "slug", "parent", "template"):
            if not meta.get(key):
                sys.exit(f"{md}: missing '{key}' in front matter")
        html = markdown_to_blocks(body)
        (OUT / (meta["slug"] + ".html")).write_text(html, encoding="utf-8")
        pages.append(meta)
    pages.sort(key=lambda m: (m["parent"], int(m.get("order", 100)), m["title"]))
    lines = ["<?php", "// Generated by tools/build_pages.py. Do not edit.", "return array("]
    for m in pages:
        lines.append(
            "\t" + php_str(m["slug"]) + " => array( "
            + ", ".join(f"{php_str(k)} => {php_str(m.get(k, ''))}" for k in ("title", "parent", "template", "icon", "excerpt", "order", "path"))
            + " ),"
        )
    lines.append(");")
    (OUT / "index.php").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(pages)} pages written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
