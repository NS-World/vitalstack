#!/usr/bin/env python3
"""Build wp-content/themes/vitalstack/data/lesson-charts.php from the lessons.

Chart sections ("## See it as a chart: ...", "## See it as a diagram: ...",
"## The workflow as a diagram") with a ::figure, and "## Common mistakes and edge
cases" text sections (4.18.0, for short interview problems), are rendered to the
same block markup the starter import uses. The theme (inc/lesson-charts.php)
adds each section to the matching lesson on the site, before its "Summary"
heading, unless that lesson already shows the figure. That way lessons
imported before the charts existed get them without a re-import, and lessons
imported later are not doubled.

Run after editing a chart section:  python3 tools/build_lesson_charts.py
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from lessons_to_wxr import markdown_to_blocks, parse_front_matter  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
LESSONS = ROOT / "content" / "lessons"
OUT = ROOT / "wp-content" / "themes" / "vitalstack" / "data" / "lesson-charts.php"
FIGS = ROOT / "wp-content" / "themes" / "vitalstack" / "assets" / "lessons"
HEAD = re.compile(r"^## (See it as a (chart|diagram)\b.*|The workflow as a diagram|Common mistakes and edge cases)$", re.M)


def php_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main():
    entries = {}
    for path in sorted(LESSONS.glob("*/*.md")):
        text = path.read_text(encoding="utf-8")
        if not HEAD.search(text):
            continue
        meta, body = parse_front_matter(text, path)
        slug = meta["slug"]
        heads = [m.start() for m in re.finditer(r"^## ", body, re.M)]
        for m in HEAD.finditer(body):
            end = next((h for h in heads if h > m.start()), len(body))
            section = body[m.start():end]
            fig = re.search(r"^::figure\s+([a-z0-9-]+\.svg)", section, re.M)
            if fig and not (FIGS / fig.group(1)).exists():
                sys.exit(f"{path}: figure {fig.group(1)} not generated")
            # Key the theme uses to see whether the lesson already has this section:
            # the chart's file name, or for a text section its heading.
            key = fig.group(1) if fig else m.group(1).strip()
            nxt = re.match(r"## (.*)", body[end:])
            anchor = nxt.group(1).strip() if nxt else ""
            entries.setdefault(slug, []).append((key, anchor, markdown_to_blocks(section)))
    lines = ["<?php", "/**", " * Chart sections for lessons. Generated by tools/build_lesson_charts.py: do not edit.",
             " *", " * @package VitalStack", " */", "", "defined( 'ABSPATH' ) || exit;", "", "return array("]
    for slug, items in entries.items():
        lines.append(f"\t{php_str(slug)} => array(")
        for fig, anchor, html in items:
            lines.append(f"\t\tarray( 'figure' => {php_str(fig)}, 'before' => {php_str(anchor)}, 'html' => {php_str(html)} ),")
        lines.append("\t),")
    lines.append(");")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{sum(len(v) for v in entries.values())} sections for {len(entries)} lessons -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
