#!/usr/bin/env python3
"""Turn content/quizzes/<subject>.md into PHP data files the theme can load fast.

Format (one file per learning path, e.g. content/quizzes/python.md):

    ## python-variables            <- the lesson slug
    Q: Which line creates a variable?
    - [ ] int x = 5
    - [x] x = 5                     <- [x] marks the correct option
    - [ ] var x := 5
    > Python creates a variable the first time you assign to it.   <- explanation

Questions are separated by a new "Q:" line. Inline `code` is allowed.
Options are shuffled at build time (stable per question); end a question
with "(keep order)" to keep the written order.

Usage:
    python3 tools/build_quizzes.py           # writes wp-content/themes/vitalstack/data/quizzes/<subject>.php
    python3 tools/build_quizzes.py --check   # also verifies every slug matches a lesson file
"""
import pathlib
import random
import re
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "content" / "quizzes"
LESSONS = ROOT / "content" / "lessons"
OUT = ROOT / "wp-content" / "themes" / "vitalstack" / "data" / "quizzes"


def php_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def parse(path):
    quizzes, slug, q = {}, None, None
    for n, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.rstrip()
        if not line.strip() or line.startswith("<!--"):
            continue
        if line.startswith("## "):
            slug = line[3:].strip()
            quizzes.setdefault(slug, [])
            q = None
        elif line.startswith("Q:"):
            if slug is None:
                sys.exit(f"{path}:{n}: question before any '## slug'")
            q = {"q": line[2:].strip(), "o": [], "a": -1, "e": ""}
            quizzes[slug].append(q)
        elif re.match(r"^- \[[ xX]\] ", line):
            if q is None:
                sys.exit(f"{path}:{n}: option before 'Q:'")
            if line[3] in "xX":
                if q["a"] != -1:
                    sys.exit(f"{path}:{n}: two correct options")
                q["a"] = len(q["o"])
            q["o"].append(line[6:].strip())
        elif line.startswith(">"):
            if q is None:
                sys.exit(f"{path}:{n}: explanation before 'Q:'")
            q["e"] = (q["e"] + " " + line[1:].strip()).strip()
        else:
            sys.exit(f"{path}:{n}: unexpected line: {line!r}")
    for slug, qs in quizzes.items():
        for i, q in enumerate(qs, 1):
            if q["a"] == -1 or len(q["o"]) < 2:
                sys.exit(f"{path}: {slug} question {i}: needs 2+ options and exactly one [x]")
            shuffle(q, slug)
    return quizzes


def shuffle(q, slug):
    """Shuffle options so the answer isn't always in the same place.

    Seeded by the lesson and question text, so every build gives the same
    order (stable daily challenges and cached pages). Questions whose options
    form a sequence (e.g. "All of the above") can opt out with "(keep order)"
    at the end of the question line.
    """
    if q["q"].endswith("(keep order)"):
        q["q"] = q["q"][: -len("(keep order)")].rstrip()
        return
    answer = q["o"][q["a"]]
    rng = random.Random(zlib.crc32((slug + "|" + q["q"]).encode("utf-8")))
    rng.shuffle(q["o"])
    q["a"] = q["o"].index(answer)


def lesson_slugs():
    slugs = {}
    for md in LESSONS.glob("*/*.md"):
        m = re.search(r"^slug:\s*(\S+)", md.read_text(encoding="utf-8"), re.M)
        if m:
            slugs[m.group(1)] = md.parent.name
    return slugs


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    check = "--check" in sys.argv
    known = lesson_slugs() if check else {}
    total = 0
    for src in sorted(SRC.glob("*.md")):
        quizzes = parse(src)
        if check:
            for slug in quizzes:
                if known.get(slug) != src.stem:
                    sys.exit(f"{src.name}: '{slug}' is not a lesson in content/lessons/{src.stem}/")
        lines = ["<?php", "// Generated by tools/build_quizzes.py from content/quizzes/" + src.name + ". Do not edit.", "return array("]
        for slug, qs in quizzes.items():
            lines.append("\t" + php_str(slug) + " => array(")
            for q in qs:
                opts = ", ".join(php_str(o) for o in q["o"])
                lines.append(f"\t\tarray( 'q' => {php_str(q['q'])}, 'o' => array( {opts} ), 'a' => {q['a']}, 'e' => {php_str(q['e'])} ),")
                total += 1
            lines.append("\t),")
        lines.append(");")
        (OUT / (src.stem + ".php")).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{src.name}: {len(quizzes)} lessons, {sum(len(v) for v in quizzes.values())} questions")
    if check:
        have = set()
        for src in SRC.glob("*.md"):
            have |= set(parse(src))
        missing = sorted(s for s in known if s not in have)
        print(f"lessons without a quiz: {len(missing)}")
        for s in missing[:40]:
            print("  ", known[s], s)
    print(f"total questions: {total}")


if __name__ == "__main__":
    main()
